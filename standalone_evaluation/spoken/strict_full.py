class ReviewError(Exception): pass

def write_json(path, obj):
    p=Path(path); p.parent.mkdir(parents=True,exist_ok=True)
    temp=p.with_name(p.name+'.tmp')
    temp.write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    temp.replace(p)

def read_json(path): return json.loads(Path(path).read_text(encoding='utf-8-sig'))

def hash_obj(obj): return hashlib.sha256(json.dumps(obj,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()).hexdigest()

def load_inputs(memory_path,transcript_path):
    memory=read_json(memory_path); transcript=read_json(transcript_path)
    facts=memory.get('source_facts'); turns=transcript.get('turns')
    if not isinstance(facts,list) or not facts: raise ReviewError('memory.json: source_facts must be a nonempty array')
    if not isinstance(turns,list) or not turns: raise ReviewError('transcript.json: turns must be a nonempty array')
    records=[]; mids=set(); source_questions={}
    for i,f in enumerate(facts):
        if not isinstance(f,dict): raise ReviewError(f'Invalid memory at index {i}')
        origin=f.get('dataset_source') or {}
        mid=f.get('dataset_memory_id') or (origin.get('dataset_memory_id') if isinstance(origin,dict) else None)
        if not isinstance(mid,str) or not mid.strip() or mid in mids: raise ReviewError(f'Missing/duplicate source Memory ID at index {i}: {mid}')
        if not isinstance(f.get('text'),str) or not f['text'].strip(): raise ReviewError(f'Blank source memory: {mid}')
        mids.add(mid)
        sq=f.get('source_question') or ''
        if sq and sq not in source_questions: source_questions[sq]='SQ%03d'%(len(source_questions)+1)
        records.append({'index':i,'memory_id':mid,'memory_text':f['text'],'source_question':sq,'source_question_id':source_questions.get(sq,'')})
    questions=[]; citations=set(); unknown=set(); per_round=[]
    rounds=set()
    for i,t in enumerate(turns):
        if not isinstance(t,dict) or not isinstance(t.get('interviewer'),str):raise ReviewError('Invalid interviewer turn at index '+str(i))
        rid=t.get('round')
        if rid in rounds: raise ReviewError('Duplicate interview round: '+str(rid))
        rounds.add(rid)
        # Numeric index generated by this program is the sole model-visible question identifier.
        questions.append({'question_index':i,'round':rid,'question_text':t['interviewer']})
        att=t.get('memory_attribution') or {}
        cited=att.get('cited_memory_ids')
        if att.get('complete') is not True or not isinstance(cited,list) or any(not isinstance(x,str) for x in cited):
            raise ReviewError('Round '+str(rid)+' lacks complete cited_memory_ids; cannot silently count missing citations as zero')
        citations.update(x for x in cited if x in mids)
        unknown.update(x for x in cited if x not in mids)
        per_round.append({'round':rid,'cited_memory_ids':sorted(set(x for x in cited if x in mids)), 'unknown_cited_memory_ids':sorted(set(x for x in cited if x not in mids))})
    return memory,transcript,records,questions,citations,unknown,per_round


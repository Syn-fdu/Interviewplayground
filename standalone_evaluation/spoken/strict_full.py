def parse_partial_model_rows(obj,records,questions):
    """Return validated rows keyed by global index, not fabricated placeholders.

    A badly formed/duplicate row is treated as missing for targeted repair.
    Valid rows survive even when the model omits others or reorders the list.
    """
    entries=obj.get('results') if isinstance(obj,dict) else None
    if not isinstance(entries,list):
        return {}
    nq=len(questions); total=len(records)
    valid={};duplicates=set()
    for item in entries:
        if not isinstance(item,dict) or set(item)!={'index','question_index','outcome','reason'}:
            continue
        idx=item['index']
        if type(idx) is not int or not(0<=idx<total):continue
        if idx in valid:
            duplicates.add(idx)
            continue
        q=item['question_index'];outcome=item['outcome'];reason=item['reason']
        if type(q) is not int or not(-1<=q<nq):continue
        if outcome not in ('direct','adjacent','none'):continue
        if not isinstance(reason,str) or not reason.strip():continue
        # The only semantically unambiguous normalization allowed:
        # outcome remains "none" while a nonnegative index is discarded.
        item=dict(item)
        if outcome=='none' and q>=0:
            item['question_index']=-1
        elif outcome!='none' and q==-1:
            # Missing semantic evidence, must request re-judgment.
            continue
        valid[idx]=item
    for idx in duplicates:
        valid.pop(idx,None)
    return valid

def salvage_json_prefix(raw):
    """Extract complete per-memory JSON objects from a truncated output.

    Never pretend the incomplete tail is complete. Only items fully parsed
    by json.JSONDecoder are candidates and each is later fully validated.
    """
    if not isinstance(raw,str):return {'results':[]}
    try:
        obj=json.loads(raw)
        if isinstance(obj,dict):return obj
    except (ValueError,TypeError):pass
    import re
    match=re.search(r'"results"\s*:\s*\[',raw)
    if not match:return {'results':[]}
    decoder=json.JSONDecoder()
    index=match.end()
    items=[]
    while index<len(raw):
        while index<len(raw) and raw[index] in ' \r\n\t,':
            index+=1
        if index>=len(raw) or raw[index] in ']}' :break
        try:
            entry,next_index=decoder.raw_decode(raw,index)
        except (ValueError,TypeError):
            break
        items.append(entry)
        index=next_index
    return {'results':items}

def score_with_targeted_missing_repairs(a,obj,records,questions,output,request,
                                        *,max_batch=MISSING_REPAIR_BATCH_SIZE):
    """Build a complete, strict result or fail with a specific missing-index list.

    A successful first all-memory request triggers ZERO extra calls.
    Repair requests contain only missing memories but ALL interviewer questions.
    """
    valid=parse_partial_model_rows(obj,records,questions)
    n=len(records)
    missing=[i for i in range(n) if i not in valid]
    original_count=len(valid)
    repair_events=[]
    if missing:
        print(f'Partial SpokenTruth response: {original_count}/{n} valid. '
              f'Targeted repair required for {len(missing)} memories.',flush=True)
    for offset in range(0,len(missing),max_batch):
        chunk=missing[offset:offset+max_batch]
        payload={
            'task':'Review only these missing Memory indexes. The rest are already accepted.',
            'question_count':len(questions),
            'actual_interviewer_questions':questions,
            'missing_memories':[{'index':i,'memory_text':records[i]['memory_text']}
                                 for i in chunk]
        }
        # Durable checkpoint before every outbound model call.
        write_json(output/'partial_review_checkpoint.json',{
            'schema':'spoken_partial_review.v1','accepted_results':list(valid.values()),
            'remaining_indexes':[i for i in range(n) if i not in valid],
            'input_count':n})
        new_result=request(payload,chunk)
        found=parse_partial_model_rows(new_result,records,questions)
        accepted=[idx for idx in chunk if idx in found]
        for idx in accepted:
            valid[idx]=found[idx]
        repair_events.append({
            'requested_indexes':chunk,'accepted_indexes':accepted,
            'unresolved_indexes':[i for i in chunk if i not in valid]})
        write_json(output/'partial_review_checkpoint.json',{
            'schema':'spoken_partial_review.v1','accepted_results':list(valid.values()),
            'remaining_indexes':[i for i in range(n) if i not in valid],
            'input_count':n})
    still_missing=[i for i in range(n) if i not in valid]
    write_json(output/'targeted_missing_repair_audit.json',{
        'initial_valid_count':original_count,
        'initial_missing_count':n-original_count,
        'repaired_count':len(valid)-original_count,
        'remaining_indexes':still_missing,
        'repair_batches':repair_events,
        'original_response_preserved':True,
        'policy':'Missing results never become inferred none decisions.'
    })
    if still_missing:
        raise ReviewError('SpokenTruth incomplete after targeted repairs: '
             f'{len(still_missing)}/{n} Memory decisions missing; indexes='+
             ','.join(map(str,still_missing[:40])))
    complete={'results':[valid[i] for i in range(n)]}
    # Keep strict final contract and semantic evidence checks.
    validate_result(complete,records,questions)
    return complete

def conflicting_indices(obj, records, questions):
    """Detect ONLY outcome/index logical contradictions, after checking all other invariants."""
    n=len(records); nq=len(questions)
    if not isinstance(obj,dict) or set(obj)!={'results'} or not isinstance(obj['results'],list) or len(obj['results'])!=n:
        raise ReviewError('Cannot targeted-repair: full result array is missing or incomplete')
    bad=[]
    for i,item in enumerate(obj['results']):
        if not isinstance(item,dict) or set(item)!={'index','question_index','outcome','reason'}:
            raise ReviewError(f'Cannot targeted-repair: invalid fields at memory {i}')
        idx,q,outcome,reason=item['index'],item['question_index'],item['outcome'],item['reason']
        if type(idx) is not int or idx!=i or type(q) is not int or not(-1<=q<nq) or outcome not in ('direct','adjacent','none') or not isinstance(reason,str) or not reason.strip():
            raise ReviewError(f'Cannot targeted-repair: other invalid data at memory {i}')
        if (outcome=='none')!=(q==-1):bad.append(i)
    return bad

def normalize_none_index(obj, records, questions):
    """Normalize unambiguous field convention, NEVER change semantic outcome.

    This does NOT validate whether a 'none' semantic judgement was correct.
    Keep original raw text and write a separate audit for all changed fields.
    """
    bad=conflicting_indices(obj,records,questions)
    normalized={'results':[dict(r) for r in obj['results']]}
    audit=[]; unresolved=[]
    for i in bad:
        item=normalized['results'][i]
        if item['outcome']=='none' and item['question_index']>=0:
            audit.append({'index':i,'memory_id':records[i]['memory_id'],
                          'original_question_index':item['question_index'],
                          'normalized_question_index':-1,'outcome_unchanged':'none'})
            item['question_index']=-1
        else:
            unresolved.append(i)
    return normalized,audit,unresolved


def write_consistency_diagnostics(output, obj, records, baseline_path=None):
    """Compare decisions with optional existing approved reference, never force its score."""
    from collections import Counter
    current=obj['results']
    counts=dict(Counter(x['outcome'] for x in current))
    diagnostic={'current_counts':counts,'baseline_used_for_scoring':False,
                'note':'A baseline is a stability diagnostic, never a ground-truth label or output target.'}
    if baseline_path and Path(baseline_path).exists():
        base=read_json(baseline_path)
        prior=base.get('model_response',base) if isinstance(base,dict) else None
        prior=prior.get('results') if isinstance(prior,dict) else None
        if isinstance(prior,list) and len(prior)==len(current) and all(isinstance(x,dict) and x.get('index')==i for i,x in enumerate(prior)):
            diffs=[]
            for i,(x,y) in enumerate(zip(prior,current)):
                if (x['outcome'],x['question_index'])!=(y['outcome'],y['question_index']):
                    diffs.append({'index':i,'memory_id':records[i]['memory_id'],
                                  'old_outcome':x['outcome'],'new_outcome':y['outcome'],
                                  'old_question_index':x['question_index'],'new_question_index':y['question_index']})
            diagnostic.update({'baseline_counts':dict(Counter(x['outcome'] for x in prior)),
                               'changed_memory_count':len(diffs),'changed_memories':diffs,
                               'high_drift_warning':len(diffs)>max(10,int(.2*len(records)))})
    write_json(output/'stability_diagnostics.json',diagnostic)
    if diagnostic.get('high_drift_warning'):
        print('WARNING: Large verdict drift from reference; inspect output/stability_diagnostics.json. No outcomes were forced.',flush=True)
    return diagnostic

def repair_disagreements(obj,records,questions,request_correction):
    """Apply only independently re-judged disputed rows; leave all others byte-equivalent."""
    bad=conflicting_indices(obj,records,questions)
    if not bad:return obj,[]
    payload={'task':'Resolve outcome/question_index contradictions for ONLY these entries. Do not change any other records.',
      'question_count':len(questions),'actual_interviewer_questions':questions,
      'disputed_memories':[{'index':i,'memory_text':records[i]['memory_text'],
          'previous_inconsistent_result':obj['results'][i]} for i in bad]}
    patch=request_correction(payload)
    if not isinstance(patch,dict) or set(patch)!={'results'} or not isinstance(patch['results'],list) or len(patch['results'])!=len(bad):
        raise ReviewError(f'Correction response must contain exactly {len(bad)} disputed results')
    updated={'results':[dict(x) for x in obj['results']]}
    for i,item in zip(bad,patch['results']):
        if not isinstance(item,dict) or set(item)!={'index','question_index','outcome','reason'} or type(item['index']) is not int or item['index']!=i:
            raise ReviewError(f'Correction has invalid/misordered index at memory {i}')
        updated['results'][i]=item
    remaining=conflicting_indices(updated,records,questions)
    if remaining:raise ReviewError('Model correction still inconsistent at memories '+','.join(map(str,remaining)))
    validate_result(updated,records,questions)
    return updated,bad

def normalize_question_reason(reason, question_index, question):
    """Display ONLY canonical interviewer round identifiers, not 0-based indexes.

    Legacy model responses often start with 'Question {question_index}'.
    Replace that exact index reference with the authoritative round ID. The
    remaining semantic reasoning is retained unchanged. No model re-evaluation.
    """
    reason=reason.strip()
    if question_index < 0:
        return reason
    label='Q'+str(question['round'])
    # Replace only the known legacy index, not unrelated numbers in prose.
    reason=re.sub(r'\bQuestion\s+'+str(question_index)+r'\b',label,reason,flags=re.IGNORECASE)
    # If model already used the correct original round ID, canonicalize that.
    reason=re.sub(r'\bQuestion\s+'+re.escape(str(question['round']))+r'\b',label,reason,flags=re.IGNORECASE)
    if not reason.startswith(label+' ') and not reason.startswith(label+':') and reason!=label:
        reason=label+': '+reason
    return reason

def validate_result(obj,records,questions):
    n=len(records); nq=len(questions)
    if not isinstance(obj,dict) or set(obj)!= {'results'}:raise ReviewError('JSON must have exactly one top-level key: results')
    res=obj['results']
    if not isinstance(res,list) or len(res)!=n:raise ReviewError(f'Coverage mismatch: expected {n} results, got {len(res) if isinstance(res,list) else "non-array"}')
    clean=[]
    for i,item in enumerate(res):
        if not isinstance(item,dict) or set(item)!={'index','question_index','outcome','reason'}:raise ReviewError(f'Result index {i} must have exactly 4 required keys')
        idx=item['index']; q=item['question_index']; outcome=item['outcome']; reason=item['reason']
        if type(idx) is not int or idx!=i:raise ReviewError(f'Result order/index mismatch: expected {i}, got {idx}')
        if type(q) is not int or not (-1<=q<nq):raise ReviewError(f'Invalid question_index at memory {i}: {q}; allowed -1..{nq-1}')
        if outcome not in ('direct','adjacent','none'):raise ReviewError(f'Invalid outcome at memory {i}: {outcome}')
        if (outcome=='none')!=(q==-1):raise ReviewError(f'Outcome/question_index disagreement at memory {i}')
        if not isinstance(reason,str) or not reason.strip():raise ReviewError(f'Empty reason at memory {i}')
        clean.append({'memory_id':records[i]['memory_id'],'memory_index':i,
          'question_id':str(questions[q]['round']) if q>=0 else '',
          'question_index':q,'question_quote':questions[q]['question_text'] if q>=0 else '',
          'outcome':outcome,'reason':normalize_question_reason(reason,q,questions[q] if q>=0 else None)})
    return clean

def unwrap(raw):
    if not isinstance(raw,str) or not raw.strip():raise ReviewError('Empty API message.content')
    try: return json.loads(raw)
    except json.JSONDecodeError as e:raise ReviewError(f'Invalid JSON at character {e.pos}: {e.msg}') from e

def request_llm(a, payload, raw_path, *, system_prompt=None, response_schema=None, schema_name=None):
    system_prompt=system_prompt if system_prompt is not None else SYSTEM
    response_schema=response_schema if response_schema is not None else schema()
    schema_name=schema_name if schema_name is not None else 'all_memory_opportunity_v3_4'
    if a.provider=='remote':
        key=os.getenv('OPENAI_API_KEY','')
        if not key:raise ReviewError('OPENAI_API_KEY is not set')
        p=urlsplit(a.base_url)
        if p.scheme!='https' or not p.netloc:raise ReviewError('Remote base URL must use HTTPS')
        url=a.base_url.rstrip('/')+'/chat/completions'
        reqobj={'model':a.model,'temperature':0,'max_tokens':a.max_output_tokens,
          'messages':[{'role':'system','content':system_prompt},{'role':'user','content':json.dumps(payload,ensure_ascii=False)}]}
        if a.response_format=='json_schema':
            reqobj['response_format']={'type':'json_schema','json_schema':{'name':schema_name,'strict':True,'schema':response_schema}}
        elif a.response_format=='json_object':reqobj['response_format']={'type':'json_object'}
        headers={'Content-Type':'application/json','Authorization':'Bearer '+key}
    else:
        url=a.base_url.rstrip('/')+'/api/chat'
        reqobj={'model':a.model,'stream':False,'format':response_schema,
         'options':{'temperature':0,'num_predict':a.max_output_tokens},
         'messages':[{'role':'system','content':system_prompt},{'role':'user','content':json.dumps(payload,ensure_ascii=False)}]}
        headers={'Content-Type':'application/json'}
    req=Request(url,data=json.dumps(reqobj,ensure_ascii=False).encode('utf-8'),headers=headers,method='POST')
    def call_api():
        with urlopen(req,timeout=a.request_timeout) as resp:
            return json.loads(resp.read().decode('utf-8'))
    try:
        body=perform_with_one_network_retry(call_api)
    except HTTPError as e:
        raise ReviewError(f'HTTP {e.code}: '+e.read(1800).decode('utf-8','replace')) from e
    except NetworkInstabilityError as e:raise ReviewError(str(e)) from e
    except (OSError,URLError,TimeoutError,ValueError) as e:raise ReviewError('Remote request failed: '+str(e)) from e
    if a.provider=='remote':
        choice=(body.get('choices') or [{}])[0]; raw=(choice.get('message') or {}).get('content')
        finish=choice.get('finish_reason')
    else:
        raw=(body.get('message') or {}).get('content'); finish=body.get('done_reason')
    raw_path.write_text(raw if isinstance(raw,str) else json.dumps(raw,ensure_ascii=False),encoding='utf-8')
    if finish in ('length','max_tokens'):raise ReviewError('Model output truncated (finish_reason='+str(finish)+'); increase --max-output-tokens / model limit')
    return unwrap(raw)

